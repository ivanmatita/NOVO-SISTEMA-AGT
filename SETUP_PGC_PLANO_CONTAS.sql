-- 1. Criar a tabela public.pgc_plano_contas caso não exista
CREATE TABLE IF NOT EXISTS public.pgc_plano_contas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    empresa_id UUID REFERENCES public.empresas(id) ON DELETE CASCADE,
    conta VARCHAR(50) NOT NULL,
    tipo VARCHAR(20) NOT NULL, -- 'GR', 'GA', 'GM', etc.
    descricao TEXT NOT NULL,
    justificacao TEXT,
    layout TEXT,
    parent_id VARCHAR(50),
    is_system BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT pgc_plano_contas_empresa_conta_key UNIQUE (empresa_id, conta)
);

-- 2. Índices de performance para busca rápida por empresa e número de conta
CREATE INDEX IF NOT EXISTS idx_pgc_plano_contas_empresa ON public.pgc_plano_contas(empresa_id);
CREATE INDEX IF NOT EXISTS idx_pgc_plano_contas_conta ON public.pgc_plano_contas(conta);

-- 3. Habilitar Níveis de Segurança RLS (Row Level Security)
ALTER TABLE public.pgc_plano_contas ENABLE ROW LEVEL SECURITY;

-- 4. Criar Políticas RLS de isolamento de dados por empresa (multi-tenant)
DROP POLICY IF EXISTS "Permitir SELECT PGC por Empresa ou Contas do Sistema" ON public.pgc_plano_contas;
CREATE POLICY "Permitir SELECT PGC por Empresa ou Contas do Sistema"
ON public.pgc_plano_contas FOR SELECT
USING (
    empresa_id IS NULL 
    OR empresa_id = (SELECT empresa_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR empresa_id = (SELECT company_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Permitir INSERT PGC por Empresa" ON public.pgc_plano_contas;
CREATE POLICY "Permitir INSERT PGC por Empresa"
ON public.pgc_plano_contas FOR INSERT
WITH CHECK (
    empresa_id = (SELECT empresa_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR empresa_id = (SELECT company_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Permitir UPDATE PGC por Empresa" ON public.pgc_plano_contas;
CREATE POLICY "Permitir UPDATE PGC por Empresa"
ON public.pgc_plano_contas FOR UPDATE
USING (
    empresa_id = (SELECT empresa_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR empresa_id = (SELECT company_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR auth.role() = 'service_role'
);

DROP POLICY IF EXISTS "Permitir DELETE PGC por Empresa" ON public.pgc_plano_contas;
CREATE POLICY "Permitir DELETE PGC por Empresa"
ON public.pgc_plano_contas FOR DELETE
USING (
    empresa_id = (SELECT empresa_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR empresa_id = (SELECT company_id FROM public.users WHERE id = auth.uid() LIMIT 1)
    OR auth.role() = 'service_role'
);

